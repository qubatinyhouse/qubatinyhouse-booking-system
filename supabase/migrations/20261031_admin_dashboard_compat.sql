-- Quba Tiny House: additive compatibility migration for existing booking databases.
-- Safe to run more than once. Does not alter existing reservations or financial records.

alter table public.seasonal_rates
  add column if not exists weekday_rate numeric(10,2),
  add column if not exists weekend_rate numeric(10,2);

create table if not exists public.blocked_dates (
  id bigint generated by default as identity primary key,
  unit_id text not null references public.units(id) on delete cascade,
  check_in date not null,
  check_out date not null,
  reason text not null default 'other' check (reason in ('owner','maintenance','other')),
  note text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  check (check_out > check_in)
);

create index if not exists blocked_dates_unit_dates_idx
  on public.blocked_dates (unit_id, check_in, check_out)
  where active = true;

alter table public.blocked_dates enable row level security;
