-- Quba Tiny House booking database (run in Supabase SQL Editor)
create extension if not exists btree_gist;

create table if not exists public.units (
  id text primary key,
  name text not null,
  unit_type text not null check (unit_type in ('small','large','aframe')),
  capacity integer not null check (capacity between 1 and 10),
  weekday_rate numeric(10,2) not null default 0,
  weekend_rate numeric(10,2) not null default 0,
  holiday_rate numeric(10,2) not null default 0,
  breakfast_rate_per_person numeric(10,2) not null default 0,
  is_demo_rate boolean not null default true,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.special_dates (
  date date primary key,
  label text not null,
  active boolean not null default true
);

create table if not exists public.seasonal_rates (
  id bigint generated by default as identity primary key,
  unit_id text not null references public.units(id) on delete cascade,
  start_date date not null,
  end_date date not null,
  nightly_rate numeric(10,2) not null check (nightly_rate > 0),
  label text not null,
  active boolean not null default true,
  check (end_date > start_date)
);

create table if not exists public.reservations (
  id uuid primary key default gen_random_uuid(),
  booking_code text not null unique default ('QTH-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10))),
  unit_id text not null references public.units(id),
  check_in date not null,
  check_out date not null,
  guest_name text not null,
  phone text not null,
  guest_count integer not null check (guest_count between 1 and 10),
  breakfast boolean not null default false,
  note text not null default '',
  stay_amount numeric(10,2) not null,
  breakfast_amount numeric(10,2) not null default 0,
  total_amount numeric(10,2) not null,
  deposit_percent integer not null check (deposit_percent in (30,40)),
  deposit_amount numeric(10,2) not null,
  remaining_amount numeric(10,2) not null,
  status text not null default 'pending_payment' check (status in ('pending_payment','confirmed','expired','cancelled','payment_failed','payment_review')),
  payment_status text not null default 'not_started',
  payment_transaction text,
  payment_error text,
  paid_amount numeric(10,2),
  paid_at timestamptz,
  expires_at timestamptz not null default (now() + interval '25 minutes'),
  created_at timestamptz not null default now(),
  check (check_out > check_in)
);

-- Strong database-level guard: two active bookings cannot overlap for the same unit.
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'reservations_no_overlapping_active') then
    alter table public.reservations add constraint reservations_no_overlapping_active
      exclude using gist (
        unit_id with =,
        daterange(check_in, check_out, '[)') with &&
      ) where (status in ('pending_payment','confirmed'));
  end if;
end $$;

create index if not exists reservations_dates_idx on public.reservations (unit_id, check_in, check_out);
create index if not exists reservations_status_expiry_idx on public.reservations (status, expires_at);
create index if not exists seasonal_rates_unit_dates_idx on public.seasonal_rates (unit_id, start_date, end_date);

